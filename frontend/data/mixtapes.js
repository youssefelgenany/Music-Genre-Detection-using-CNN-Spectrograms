function genreToCoverFile(genre) {
  return String(genre ?? "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

export const mixtapes = baseMixtapes.map((entry) => ({
  ...entry,
  cover: `/covers/${genreToCoverFile(entry.genre)}.jpg`,
}));

function normalizeGenre(genre) {
  return String(genre ?? "").trim().toLowerCase();
}

function withGenre(song, genre) {
  return {
    ...song,
    genre,
  };
}

const allSongs = mixtapes.flatMap(({ genre, songs }) =>
  (songs ?? []).map((song) => withGenre(song, genre)),
);

const duplicateSongIds = (() => {
  const seen = new Set();
  const duplicates = new Set();
  for (const song of allSongs) {
    const id = String(song?.id ?? "").trim();
    if (!id) continue;
    if (seen.has(id)) duplicates.add(id);
    else seen.add(id);
  }
  return [...duplicates];
})();

if (duplicateSongIds.length > 0) {
  throw new Error(
    `Duplicate mixtape song IDs detected: ${duplicateSongIds.join(", ")}`,
  );
}

/**
 * Get all songs in one flat collection (each song includes its genre).
 * @returns {Array<{ id: string, title: string, artist: string, audio: string, cover: string, duration: string, genre: string }>}
 */
export function getAllSongs() {
  return allSongs.map((song) => ({ ...song }));
}

/**
 * Get songs for one genre (case-insensitive).
 * @param {string} genre
 * @returns {Array<{ id: string, title: string, artist: string, audio: string, cover: string, duration: string, genre: string }>}
 */
export function getSongsByGenre(genre) {
  const wantedGenre = normalizeGenre(genre);
  if (!wantedGenre) return [];
  return allSongs
    .filter((song) => normalizeGenre(song.genre) === wantedGenre)
    .map((song) => ({ ...song }));
}
